#!/usr/bin/env python3
"""A-06: The built-in sound is a const array generated from a source WAV and stored in firmware flash.

Why: computing it at runtime took 237-316 ms per wake (DL-008); flash can't be lost to a bad transfer.
Scope: firmware/*/src/sounds/*.h and sounds/*.wav.
How: every header in a firmware sounds/ folder must be byte-identical to what tools/wav2header.py
generates from its source WAV in sounds/, and the source WAV must meet budget B-02. A hand-edited,
orphaned or out-of-date header fails.
"""
import os
import re
import sys
from common import finish, parse_root, read

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "tools"))
import wav2header  # noqa: E402  (repo tool, standard library only)

SOURCE_RE = re.compile(r"^// GENERATED by tools/wav2header\.py from (sounds/[^ ]+\.wav)")


def main():
    root = parse_root(__doc__.splitlines()[0])
    violations, checked = [], 0
    fw = os.path.join(root, "firmware")
    for unit in sorted(os.listdir(fw)) if os.path.isdir(fw) else []:
        sdir = os.path.join(fw, unit, "src", "sounds")
        if not os.path.isdir(sdir):
            continue
        for name in sorted(os.listdir(sdir)):
            if not name.endswith(".h"):
                continue
            checked += 1
            hpath = os.path.join(sdir, name)
            rel = os.path.relpath(hpath, root)
            text = read(hpath)
            m = SOURCE_RE.match(text)
            if not m:
                violations.append(f"{rel}: not generated by tools/wav2header.py (no GENERATED header line)")
                continue
            wav = os.path.join(root, m.group(1))
            if not os.path.isfile(wav):
                violations.append(f"{rel}: source {m.group(1)} is missing")
                continue
            with open(wav, "rb") as f:
                data = f.read()
            problems = wav2header.wav_problems(data)
            if problems:
                violations.append(f"{m.group(1)} breaks budget B-02: " + "; ".join(problems))
            if text != wav2header.render_header(wav, data):
                violations.append(f"{rel}: doesn't match {m.group(1)} - regenerate it, never hand-edit (A-06)")
    finish("A-06", violations, f"{checked} built-in sound header(s) match their source WAVs")


if __name__ == "__main__":
    main()
