#!/usr/bin/env python3
"""Convert a WAV in sounds/ into a generated C++ header holding a const byte array in flash.

Usage:  python3 tools/wav2header.py sounds/builtin_dingdong.wav firmware/doorbell/src/sounds/builtin_dingdong.h

The WAV is the source; the header is generated and must never be edited by hand (absolute A-06).
The WAV must meet budget B-02: PCM, 24,000 Hz, 16-bit, mono, at most 3.0 seconds.
Standard library only (absolute A-08).
"""
import os
import re
import struct
import sys

SAMPLE_RATE, BITS, CHANNELS, MAX_SECONDS = 24000, 16, 1, 3.0
MAX_BYTES = 44 + int(SAMPLE_RATE * MAX_SECONDS) * CHANNELS * (BITS // 8)   # 144,044 (B-02)


def wav_problems(data):
    """Return a list of reasons the WAV breaks B-02 (empty list = OK)."""
    p = []
    if len(data) < 44 or data[0:4] != b"RIFF" or data[8:12] != b"WAVE":
        return ["not a RIFF/WAVE file"]
    pos, fmt, data_len = 12, None, None
    while pos + 8 <= len(data):
        cid, size = data[pos:pos + 4], struct.unpack("<I", data[pos + 4:pos + 8])[0]
        if cid == b"fmt ":
            fmt = struct.unpack("<HHIIHH", data[pos + 8:pos + 24])
        elif cid == b"data":
            data_len = size
        pos += 8 + size + (size & 1)
    if fmt is None or data_len is None:
        return ["missing fmt or data chunk"]
    audio_format, channels, rate, _byte_rate, _align, bits = fmt
    if audio_format != 1:
        p.append(f"audio format {audio_format}, expected 1 (PCM)")
    if rate != SAMPLE_RATE:
        p.append(f"sample rate {rate}, expected {SAMPLE_RATE}")
    if bits != BITS:
        p.append(f"{bits}-bit, expected {BITS}-bit")
    if channels != CHANNELS:
        p.append(f"{channels} channels, expected mono")
    seconds = data_len / float(rate * channels * max(bits // 8, 1)) if rate else 0
    if seconds > MAX_SECONDS:
        p.append(f"{seconds:.2f} s long, limit {MAX_SECONDS} s")
    if len(data) > MAX_BYTES:
        p.append(f"{len(data)} bytes, limit {MAX_BYTES}")
    return p


def symbol_for(wav_path):
    base = os.path.splitext(os.path.basename(wav_path))[0]
    return re.sub(r"[^A-Za-z0-9_]", "_", base)


def render_header(wav_path, data):
    sym = symbol_for(wav_path)
    src = "sounds/" + os.path.basename(wav_path)
    lines = [
        f"// GENERATED by tools/wav2header.py from {src} - DO NOT EDIT (absolute A-06).",
        f"// Regenerate: python3 tools/wav2header.py {src} <this file>",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        f"static const size_t {sym}_wav_len = {len(data)};",
        f"static const uint8_t {sym}_wav[{len(data)}] = {{",
    ]
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 2
    wav_path, out_path = argv[1], argv[2]
    with open(wav_path, "rb") as f:
        data = f.read()
    problems = wav_problems(data)
    if problems:
        print(f"{wav_path} breaks budget B-02: " + "; ".join(problems))
        return 1
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(render_header(wav_path, data))
    print(f"wrote {out_path} ({len(data)} bytes of audio data)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
